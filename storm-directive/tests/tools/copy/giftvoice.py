"""Builds web/js/giftvoice.js (the approved per-sample gift lines on Feat cards) from the redesign docs.
   python3 tests/tools/copy/giftvoice.py
Sources (the user approved both on 20 Oct 2026; they win over Card_Copy_Draft_All.xlsx for every Feat they cover):
  - redesign docs/GIFT_LINES.md: the 31 shared gifts, ten lines each (7 samples + Not of This World's three registers).
  - redesign docs/FEATS.md section 3: the eight sample-exclusive gift lines (one sample each; X8 has three).
No dependencies (plain text parsing), so it runs anywhere python3 does."""
import os, re, json, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '../../..'))
DOCS = os.path.normpath(os.path.join(ROOT, '../redesign docs'))
OUT = os.path.join(ROOT, 'web/js/giftvoice.js')
ROWS = ['Baseline', 'Alpha', 'Beta', 'Private Schooled', 'Ordered Online', 'Redtail', 'Prawn Again', 'NOTW Fire', 'NOTW Static', 'NOTW Alien']
# Doc name -> the card title the game shows (none differ since decision 45).
RENAME = {}
# Exclusive gift -> the column it speaks in (CV_COLS order in cardvoice.js); X8 uses the last three.
EXCL = {'X1': 0, 'X2': 1, 'X3': 2, 'X4': 3, 'X5': 4, 'X6': 5, 'X7': 6}

table = {}
cur = None
for line in open(os.path.join(DOCS, 'GIFT_LINES.md'), encoding='utf-8'):
    m = re.match(r'## (G|F)\d+\. (.+?)\s*$', line)
    if m: cur = RENAME.get(m.group(2), m.group(2)); table[cur] = [''] * 10; continue
    m = re.match(r'\| (.+?) \| "(.*)" \|\s*$', line)
    if m and cur and m.group(1) in ROWS: table[cur][ROWS.index(m.group(1))] = m.group(2)
for k, v in table.items():
    if '' in v: sys.exit('missing line in GIFT_LINES.md for ' + k)

feats = open(os.path.join(DOCS, 'FEATS.md'), encoding='utf-8').read()
for m in re.finditer(r'### (X[1-8])\. (.+?) \(.*?\n- \*\*Gift line(.*?)\n', feats):
    xid, name, rest = m.group(1), m.group(2).strip(), m.group(3)
    v = [''] * 10
    if xid in EXCL: v[EXCL[xid]] = re.search(r'"(.+)"', rest).group(1)
    else:
        for i, reg in enumerate(['Fire', 'Static', 'Alien']): v[7 + i] = re.search(reg + r' "(.+?)"', rest).group(1)
    table[name] = v
if sum(1 for k in table if table[k].count('') >= 7) != 8: sys.exit('expected 8 exclusive gifts in FEATS.md section 3')

# Alpha's Red Flagship Lv 3 lines (SAMPLES.md 2, Upgrade voice): only the Alpha column of those promise cards changes.
alpha = {}
for m in re.finditer(r'^  - (Overclocked|Critical Error|Dead Pixels): "(.+?)" /', open(os.path.join(DOCS, 'SAMPLES.md'), encoding='utf-8').read(), re.M):
    alpha[m.group(1)] = m.group(2)
if len(alpha) != 3: sys.exit('expected 3 Red Flagship Lv 3 lines in SAMPLES.md')

body = ',\n'.join(f'  {json.dumps("feat:" + k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}' for k, v in table.items())
wup = '\n'.join(f'  if (CARD_VOICE[{json.dumps("wup:" + k)}]) CARD_VOICE[{json.dumps("wup:" + k)}][1] = {json.dumps(v, ensure_ascii=False)};' for k, v in alpha.items())
open(OUT, 'w', encoding='utf-8').write(f"""'use strict';
// Spawn Prawn - gift voice lines (giftvoice.js): the approved per-sample gift line on every Feat card (redesign docs
// GIFT_LINES.md and FEATS.md section 3, approved 20 Oct 2026). They replace cardvoice.js's Feat lines from the sheet.
// GENERATED by tests/tools/copy/giftvoice.py: edit the docs and rerun, don't hand-edit the table.
// Each value is ten lines in CV_COLS order (cardvoice.js); a sample-exclusive gift has a line only in its owner's column.
// Hooks: none. Loads after cardvoice.js and writes into CARD_VOICE, so cardLine / cardVoice pick these up. Save data: none.
(function () {{
  if (typeof CARD_VOICE === 'undefined') return;
  Object.assign(CARD_VOICE, {{
{body}
  }});
  // Alpha's Red Flagship Lv 3 promise lines (SAMPLES.md 2, Upgrade voice).
{wup}
}})();
""")
print(f'giftvoice.js: {len(table)} Feats')
