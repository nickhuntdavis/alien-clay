"""Builds web/js/cardvoice.js (the per-sample consciousness line on every v10 card) from Card_Copy_Draft_All.xlsx.
   python3 tests/tools/copy/cardvoice.py [sheet.xlsx]
Keys are the card's displayed title: 'feat:<name>', 'mut:<title>', 'combo:<name>', 'mod:<name>', 'wup:<branch card name>',
plus 'mut:*catalyst' and 'mut:*concentration' for the generated cards.
FEAT LINES ARE NOT OWNED HERE (decision 46): giftvoice.py writes them from redesign docs GIFT_LINES.md and FEATS.md 3 and
overrides the sheet's Feats tab; run giftvoice.py after this script. The sheet still owns mutations, combos, modifiers, weapons. Rows marked "Reject" are left out; text typed in
"Your edits" is not parsed (edit the line cells themselves)."""
import sys, os, json
import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '../../..'))
X = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'Card_Copy_Draft_All.xlsx')
OUT = os.path.join(ROOT, 'web/js/cardvoice.js')
COLS = ['Baseline line', 'Alpha line', 'Beta line', 'Private Schooled line', 'Ordered Online line', 'Redtail line', 'Prawn Again line',
        'Not of This World (Fire) line', 'Not of This World (Static) line', 'Not of This World (Alien) line']
KIND = {'Feats': 'feat', 'Mutations': 'mut', 'Combos': 'combo', 'Modifiers': 'mod'}

wb = openpyxl.load_workbook(X)
table, n = {}, 0
for ws in wb.worksheets[1:]:
    kind = KIND.get(ws.title, 'wup' if ws.title.startswith('Weapons') else None)
    if not kind: continue
    h = [c.value for c in ws[1]]
    for r in ws.iter_rows(min_row=2, values_only=True):
        d = dict(zip(h, r))
        if (d.get('Your call') or '').strip().lower() == 'reject': continue
        name = d['Proposed name']
        if kind == 'mut' and d.get('Group') == 'Template':
            name = '*catalyst' if 'Catalyst' in (d['Current name'] or '') else '*concentration'
        lines = [(d.get(c) or '').strip() for c in COLS]
        lines = ['' if l.startswith('(exclusive') else l for l in lines]
        key = kind + ':' + name
        if key in table: sys.exit('duplicate key ' + key)
        table[key] = lines; n += 1

body = ',\n'.join(f'  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}' for k, v in table.items())
open(OUT, 'w').write(f"""'use strict';
// Spawn Prawn - card voice lines (cardvoice.js): the consciousness's one-liner on every v10 card, one per sample
// (CONSCIOUSNESS.md, decision 39), with three for Not of This World picked by its active damage type (decision 42).
// GENERATED by tests/tools/copy/cardvoice.py from Card_Copy_Draft_All.xlsx: edit the sheet and rerun, don't hand-edit the table.
// Keys are the card's shown title ('feat:', 'mut:', 'combo:', 'mod:', 'wup:'); each value is the ten lines in CV_COLS order.
// Shown in the card's quip line (ui.js .cquip). Hooks: draft.js cardOpt and weapon fork cards, weapons24.js wupForkCards,
// modcards.js modCard, combos.js optCombo -> cardLine / cardVoice. Save data: none.
const CV_COLS = ['baseline', 'alpha', 'beta', 'private', 'ordered', 'redtail', 'prawn', 'alien_fire', 'alien_static', 'alien_soul'];
const CV_ALIEN = {{ flame: 'alien_fire', shock: 'alien_static', soul: 'alien_soul' }}; // (samples10.js S10_BY.alien.shift)
const CARD_VOICE = {{
{body}
}};
// The line for this run's sample ('' when there is none, e.g. a sample-only Feat for another sample, or on the title screen).
function cardLine(key) {{
  const v = CARD_VOICE[key]; if (!v) return '';
  let s = (typeof s10Of === 'function' && s10Of()) || 'baseline';
  if (s === 'alien') {{
    const t = G && G.s10 && typeof S10_BY !== 'undefined' && S10_BY.alien && S10_BY.alien.shift ? S10_BY.alien.shift[G.s10.shiftI || 0] : 'soul';
    s = CV_ALIEN[t] || 'alien_soul';
  }}
  const i = CV_COLS.indexOf(s);
  return i >= 0 ? v[i] : '';
}}
// A draft card (draft.js card shape) -> its line. Feat rank-ups and cards without a line get ''.
function cardVoice(c) {{
  if (!c) return '';
  if (c.slot === 'feat') {{
    if (c.kind !== 'acquire') return '';
    const l = cardLine('feat:' + c.title); if (l || CARD_VOICE['feat:' + c.title]) return l;
    const d = typeof F10 !== 'undefined' && Object.values(F10).find(d => d.name === c.title); // (a Feat not in the sheet keeps its old line)
    return d && d.line ? String(d.line).replace(/^"|"$/g, '') : '';
  }}
  if (c.family === 'catalyst') return cardLine('mut:*catalyst');
  if (c.family && c.family.indexOf('conc:') === 0) return cardLine('mut:*concentration');
  return cardLine('mut:' + c.title);
}}
""")
print(f'cardvoice.js: {n} cards')
