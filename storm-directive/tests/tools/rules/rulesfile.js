// Reads and writes web/js/cardrules.js (CARD_RULES.md): the rule list and CARD_RULES_OWNS (which game tables the rules replace).
const fs = require('fs'), path = require('path');
const FILE = path.resolve(__dirname, '../../../web/js/cardrules.js');
function read() {
  const s = fs.readFileSync(FILE, 'utf8');
  const rules = new Function(s.replace(/^'use strict';/, '') + '\nreturn CARD_RULES;')();
  let owns = {}; try { owns = new Function(s.replace(/^'use strict';/, '') + '\nreturn typeof CARD_RULES_OWNS !== "undefined" ? CARD_RULES_OWNS : {};')(); } catch (e) { }
  return { rules, owns };
}
function write(rules, owns, note) {
  const n = rules.length, by = {}; for (const r of rules) by[r.src || 'planner'] = (by[r.src || 'planner'] || 0) + 1;
  const body = rules.map(x => '  ' + JSON.stringify(x) + ',').join('\n');
  fs.writeFileSync(FILE, `'use strict';\n// Spawn Prawn - card rules data (CARD_RULES.md). GENERATED by tests/tools/rules/genrules.js (the Loadout Planner's saved rules) and\n// tests/tools/rules/importtables.js (the game tables below); do not edit by hand. ${n} rules: ${Object.entries(by).map(([k, v]) => v + ' ' + k).join(', ')}.\n// Written ${new Date().toISOString().slice(0, 10)}${note ? ': ' + note : ''}.\n// CARD_RULES_OWNS: the game tables these rules replace as dealing filters (moddead.js MOD_DEAD, matrixna.js MATRIX_NA, dlvrun.js DLV.deny).\nconst CARD_RULES_OWNS = ${JSON.stringify(owns || {})};\nconst CARD_RULES = [\n${body}\n];\n`);
  return FILE;
}
module.exports = { FILE, read, write };
